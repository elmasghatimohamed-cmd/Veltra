CREATE TABLE conducteurs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(255) NOT NULL,
    prenom VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    telephone VARCHAR(255) NOT NULL,
    numero_permis VARCHAR(255) NOT NULL,

    CONSTRAINT uk_conducteur_email UNIQUE (email),
    CONSTRAINT uk_conducteur_permis UNIQUE (numero_permis)
);

CREATE TABLE passagers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(255) NOT NULL,
    prenom VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    telephone VARCHAR(255) NOT NULL,

    CONSTRAINT uk_passager_email UNIQUE (email)
);

CREATE TABLE vehicules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    marque VARCHAR(255) NOT NULL,
    modele VARCHAR(255) NOT NULL,
    immatriculation VARCHAR(30) NOT NULL,
    couleur VARCHAR(255),
    capacite INTEGER NOT NULL,
    conducteur_id BIGINT NOT NULL,

    CONSTRAINT uk_vehicule_immatriculation
        UNIQUE (immatriculation),

    CONSTRAINT fk_vehicule_conducteur
        FOREIGN KEY (conducteur_id)
            REFERENCES conducteurs(id)
);

CREATE TABLE trajets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_depart TIMESTAMP(6) NOT NULL,
    places_proposees INTEGER NOT NULL,
    statut VARCHAR(20) NOT NULL,
    conducteur_id BIGINT NOT NULL,
    vehicule_id BIGINT NOT NULL,

    CONSTRAINT fk_trajet_conducteur
        FOREIGN KEY (conducteur_id)
            REFERENCES conducteurs(id),

    CONSTRAINT fk_trajet_vehicule
        FOREIGN KEY (vehicule_id)
            REFERENCES vehicules(id)
);

CREATE TABLE points_arret (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ville VARCHAR(255) NOT NULL,
    ordre INTEGER NOT NULL,
    heure_passage TIMESTAMP(6) NOT NULL,
    prix_depuis_depart NUMERIC(10,2) NOT NULL,
    trajet_id BIGINT NOT NULL,

    CONSTRAINT uk_arret_trajet_ordre
        UNIQUE (trajet_id, ordre),

    CONSTRAINT uk_arret_trajet_ville
        UNIQUE (trajet_id, ville),

    CONSTRAINT fk_arret_trajet
        FOREIGN KEY (trajet_id)
            REFERENCES trajets(id)
);

CREATE TABLE reservations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_places INTEGER NOT NULL,
    montant_total NUMERIC(10,2) NOT NULL,
    date_reservation TIMESTAMP(6) NOT NULL,
    statut VARCHAR(20) NOT NULL,
    passager_id BIGINT NOT NULL,
    trajet_id BIGINT NOT NULL,
    point_montee_id BIGINT NOT NULL,
    point_descente_id BIGINT NOT NULL,

    CONSTRAINT fk_reservation_passager
        FOREIGN KEY (passager_id)
            REFERENCES passagers(id),

    CONSTRAINT fk_reservation_trajet
         FOREIGN KEY (trajet_id)
            REFERENCES trajets(id),

    CONSTRAINT fk_reservation_montee
        FOREIGN KEY (point_montee_id)
            REFERENCES points_arret(id),

    CONSTRAINT fk_reservation_descente
        FOREIGN KEY (point_descente_id)
            REFERENCES points_arret(id)
);
